auto obj = convert(czt(heart, true));

int width, height;
float scale;

Shader planeShader, lineShader;
extern uint planeVAO, planeVBO;
extern uint lineVAO, lineVBO;

void shaderInit() {
    planeShader = Shader("shaders/input.vs", "shaders/plane.fs");
    lineShader = Shader("shaders/input.vs", "shaders/line.fs");
}

float t = 0;

vector<cf> pts;
void render(float step) {
    planeShader.enable();

    t += step;

    for (int i = 0; i < obj.size(); ++i) {
        planeShader.setFloat("phi[" + std::to_string(i) + "]", obj[i].phi + obj[i].v * t);
    }

    glBindVertexArray(planeVAO);
    glDrawArrays(GL_TRIANGLES, 0, 6);
    glBindVertexArray(0);

    lineShader.enable();

    cf p = 0.0f;
    for (auto [r, phi, v] : obj) {
        p += r * std::polar(1.0f, phi + v * t);
    }
    p /= scale;
    p.real(p.real() / width * height);

    glBindVertexArray(lineVAO);
    if (t <= 2 * pi + 0.01) {
        pts.push_back(p);
    }
    for (int i = 0; i < pts.size() - 1; ++i) {
        line = {
            pts[i].real(), pts[i].imag(),
            pts[i + 1].real(), pts[i + 1].imag(),
        };

        glBindBuffer(GL_ARRAY_BUFFER, lineVBO);
        glBufferSubData(GL_ARRAY_BUFFER, 0, 4 * sizeof(float), &line[0]);
        glBindBuffer(GL_ARRAY_BUFFER, 0);
        glDrawArrays(GL_LINES, 0, 2);
    }
    glBindVertexArray(0);
}

